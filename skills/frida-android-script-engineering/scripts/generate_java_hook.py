#!/usr/bin/env python3
"""Generate a read-only, overload-specific Frida Java hook for an authorized app.

This deliberately logs no arguments or return values. The output is a starting
point that must be tested against a real class/method from a matching app build.
"""
from __future__ import annotations
import argparse
import json
from pathlib import Path
import sys


def generate(class_name: str, method: str, args: list[str], max_events: int, mode: str) -> str:
    if not class_name.strip() or not method.strip():
        raise ValueError("class and method must be non-empty")
    if not 1 <= max_events <= 10000:
        raise ValueError("max-events must be between 1 and 10000")
    if mode not in {"repl", "api"}:
        raise ValueError("mode must be repl or api")
    config = json.dumps({"className": class_name, "methodName": method,
                         "argTypes": args, "maxEvents": max_events}, indent=2)
    header = ("import Java from 'frida-java-bridge';\n"
              if mode == "api" else "'use strict';\n")
    return f"""/* Autogenerated metadata-only Frida hook. Verify class/overload on your owned APK. */
{header}
const CONFIG = {config};
function emit(payload) {{ try {{ send(payload); }} catch (_) {{}} }}
emit({{ event: 'script-ready', stage: 'agent-loaded' }});
if (typeof Java === 'undefined' || !Java.available) {{
  emit({{ event: 'script-error', status: 'Java VM or bridge unavailable' }});
}} else {{
  Java.perform(function () {{
    try {{
      const Cls = Java.use(CONFIG.className);
      const method = Cls[CONFIG.methodName];
      const original = method.overload.apply(method, CONFIG.argTypes);
      let seen = 0;
      original.implementation = function () {{
        const callArgs = Array.prototype.slice.call(arguments);
        try {{
          return original.call(this, ...callArgs);
        }} finally {{
          try {{
            seen += 1;
            if (seen <= CONFIG.maxEvents) {{
              emit({{ event: 'java-invocation', class_name: CONFIG.className,
                     method: CONFIG.methodName, count: seen }});
            }}
          }} catch (_) {{}}
        }}
      }};
      emit({{ event: 'hook-installed', class_name: CONFIG.className,
             method: CONFIG.methodName, max_events: CONFIG.maxEvents }});
    }} catch (_) {{
      emit({{ event: 'hook-install-failed', status: 'Class/overload lookup failed' }});
    }}
  }});
}}
"""


def main() -> int:
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--class", dest="class_name", required=True, help="Verified dotted Java class name")
    p.add_argument("--method", required=True, help="Exact Java method name or $init")
    p.add_argument("--arg", action="append", default=[], help="Full Java argument type; repeat in order")
    p.add_argument("--max-events", type=int, default=50)
    p.add_argument("--mode", choices=("repl", "api"), default="repl",
                   help="REPL JS or bridge-imported agent requiring compilation")
    p.add_argument("--out", required=True, type=Path)
    args = p.parse_args()
    try:
        code = generate(args.class_name, args.method, args.arg, args.max_events, args.mode)
    except ValueError as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 2
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(code, encoding="utf-8")
    print(f"Generated {args.mode} agent: {args.out} ({len(code)} characters)")
    print("Unverified against target APK. Confirm overload and run a controlled app smoke test.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
